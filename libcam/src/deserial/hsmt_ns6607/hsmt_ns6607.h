/*
* Write a sequence of HSMT remote messages.
*
* Sends one or more bulk-formatted command packets to remote targets
* behind the deserializer via I2C tunneling.
*
* Parameters:
* - fd           : I2C device file descriptor
* - local_addr   : deserializer local I2C address (e.g. 0x52)
* - tx_map       : bitmask of target TX channels (bit0..bit3 => TX0..TX3)
* - port_id      : remote port ID (e.g. PORT_SER=1, PORT_SENSOR=5, PORT_STD=0)
* - buf_len      : total length of cmds_buf in bytes
* - cmds_buf     : pointer to concatenated command packets
* - fail_line_no : out, 1-based index of the packet that failed (optional, may be NULL)
* - err_offset   : out, byte offset in cmds_buf where error occurred (optional, may be NULL)
*
* Returns:
* - RET_OK (0) on success
* - Negative error code (RET_*) on failure
*/
